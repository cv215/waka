"""Generates the WAKA logo files from one geometry: the W drawn as a road (dashed centre line), a filled dot for the
departure and a ring for the arrival. Writes the SVG files (docs/marque), the Android launcher vector and the web icons
(PNG, with Pillow). Run again after any change of shape or colour:

    python tools/generate_brand_assets.py
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parent.parent
# The road through the W, in a 100 x 100 icon box.
W = [(20, 34), (35, 70), (50, 44), (65, 70), (80, 34)]
ROAD, MARK, DOT, RING, RING_LINE = 12, 2, 8, 7.5, 4
DASH, GAP = 4.5, 3.5
THEMES = {
    # background, road, marking, departure, arrival fill, arrival ring
    'clair': ('#FFFFFF', '#111111', '#FFFFFF', '#111111', '#FFFFFF', '#111111'),
    'sombre': ('#111111', '#FFFFFF', '#111111', '#FFFFFF', '#111111', '#FFFFFF'),
    'cameroun': ('#007A5E', '#FCD116', '#007A5E', '#FCD116', '#CE1126', '#FCD116'),
}


def dashes(points, dash=DASH, gap=GAP):
    """Dash segments along the polyline, the pattern running on through the corners."""
    out, phase, on = [], 0.0, True
    for (x1, y1), (x2, y2) in zip(points, points[1:]):
        length = math.hypot(x2 - x1, y2 - y1)
        at = 0.0
        while at < length:
            step = min((dash if on else gap) - phase, length - at)
            if on:
                a, b = at / length, (at + step) / length
                out.append(((x1 + (x2 - x1) * a, y1 + (y2 - y1) * a), (x1 + (x2 - x1) * b, y1 + (y2 - y1) * b)))
            at += step
            phase += step
            if phase >= (dash if on else gap) - 1e-9:
                phase, on = 0.0, not on
    return out


def svg_icon(theme, size=100):
    bg, road, mark, dot, ring_fill, ring = THEMES[theme]
    pts = ' '.join(f'{x},{y}' for x, y in W)
    (sx, sy), (ex, ey) = W[0], W[-1]
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 100 100">
  <rect x="0" y="0" width="100" height="100" rx="24" fill="{bg}"/>
  <polyline points="{pts}" fill="none" stroke="{road}" stroke-width="{ROAD}" stroke-linecap="round" stroke-linejoin="round"/>
  <polyline points="{pts}" fill="none" stroke="{mark}" stroke-width="{MARK}" stroke-dasharray="{DASH} {GAP}" stroke-linejoin="round"/>
  <circle cx="{sx}" cy="{sy}" r="{DOT}" fill="{dot}"/>
  <circle cx="{ex}" cy="{ey}" r="{RING}" fill="{ring_fill}" stroke="{ring}" stroke-width="{RING_LINE}"/>
</svg>
'''


def svg_mark():
    """The symbol alone, transparent, for documents on white."""
    return svg_icon('clair').replace('<rect x="0" y="0" width="100" height="100" rx="24" fill="#FFFFFF"/>\n  ', '')


def android_vector():
    bg, road, mark, dot, ring_fill, ring = THEMES['clair']
    k = 1.08  # 100 -> 108 viewport
    p = lambda x, y: f'{x * k:.2f},{y * k:.2f}'
    line = 'M' + 'L'.join(p(x, y) for x, y in W)
    marks = ''.join(f'M{p(*a)}L{p(*b)}' for a, b in dashes(W))
    (sx, sy), (ex, ey) = W[0], W[-1]
    circle = lambda x, y, r: f'M{(x - r) * k:.2f},{y * k:.2f}a{r * k:.2f},{r * k:.2f} 0 1,0 {2 * r * k:.2f},0a{r * k:.2f},{r * k:.2f} 0 1,0 {-2 * r * k:.2f},0'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_brand_assets.py: the W road logo (light theme). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{bg}" android:pathData="M0,0h108v108h-108z" />
    <path android:fillColor="@android:color/transparent" android:pathData="{line}" android:strokeColor="{road}"
        android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeWidth="{ROAD * k:.2f}" />
    <path android:fillColor="@android:color/transparent" android:pathData="{marks}" android:strokeColor="{mark}"
        android:strokeLineCap="butt" android:strokeWidth="{MARK * k:.2f}" />
    <path android:fillColor="{dot}" android:pathData="{circle(sx, sy, DOT)}" />
    <path android:fillColor="{ring_fill}" android:pathData="{circle(ex, ey, RING)}" android:strokeColor="{ring}"
        android:strokeWidth="{RING_LINE * k:.2f}" />
</vector>
'''


def png_icon(theme, size, path, rounded=True):
    from PIL import Image, ImageDraw
    s = 8  # supersampling, then reduced: smooth edges
    big = size * s
    f = big / 100
    bg, road, mark, dot, ring_fill, ring = THEMES[theme]
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle((0, 0, big - 1, big - 1), radius=24 * f, fill=bg)
    else:
        d.rectangle((0, 0, big, big), fill=bg)
    pts = [(x * f, y * f) for x, y in W]
    d.line(pts, fill=road, width=round(ROAD * f), joint='curve')
    for x, y in pts:
        r = ROAD * f / 2
        d.ellipse((x - r, y - r, x + r, y + r), fill=road)
    for a, b in dashes(W):
        d.line([(a[0] * f, a[1] * f), (b[0] * f, b[1] * f)], fill=mark, width=max(1, round(MARK * f)))
    (sx, sy), (ex, ey) = pts[0], pts[-1]
    r = DOT * f
    d.ellipse((sx - r, sy - r, sx + r, sy + r), fill=dot)
    r, w = RING * f, RING_LINE * f
    d.ellipse((ex - r - w / 2, ey - r - w / 2, ex + r + w / 2, ey + r + w / 2), fill=ring)
    d.ellipse((ex - r + w / 2, ey - r + w / 2, ex + r - w / 2, ey + r - w / 2), fill=ring_fill)
    img.resize((size, size), Image.LANCZOS).save(path)


def main():
    marque = ROOT / 'docs' / 'marque'
    marque.mkdir(parents=True, exist_ok=True)
    (marque / 'waka-symbole.svg').write_text(svg_mark(), encoding='utf-8')
    for theme in THEMES:
        (marque / f'waka-icone-{theme}.svg').write_text(svg_icon(theme), encoding='utf-8')
    mobile = ROOT / 'apps' / 'mobile'
    (mobile / 'android/app/src/main/res/drawable/waka_launcher.xml').write_text(android_vector(), encoding='utf-8')
    icons = mobile / 'web' / 'icons'
    icons.mkdir(exist_ok=True)
    png_icon('clair', 192, icons / 'Icon-192.png')
    png_icon('clair', 512, icons / 'Icon-512.png')
    png_icon('clair', 512, icons / 'Icon-maskable-512.png', rounded=False)
    png_icon('clair', 180, icons / 'apple-touch-icon.png', rounded=False)
    png_icon('clair', 48, mobile / 'web' / 'favicon.png')
    print('ok')


if __name__ == '__main__':
    main()
